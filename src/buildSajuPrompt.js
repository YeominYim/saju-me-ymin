// 혹시 남은 AI 티(**강조, 불필요 괄호 등)를 결과에서 정리
export function cleanSajuText(text) {
  if (!text) return text

  return text
    // **강조** / __강조__ 제거
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/__([^_]+)__/g, '$1')
    // *기울임* 제거 (목록 기호 - 는 유지)
    .replace(/(?<!\w)\*([^*\n]+)\*(?!\w)/g, '$1')
    // 용어(한자) / 용어(English) 형태 괄호 설명 제거
    .replace(/([\uac00-\ud7a3A-Za-z]+)\((?:[\u4e00-\u9fff·\s]+|[A-Za-z][A-Za-z\s/&\-]*)\)/g, '$1')
    // 빈 강조 잔여물
    .replace(/\*{1,2}/g, '')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/ \n/g, '\n')
    .trim()
}
